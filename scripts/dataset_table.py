"""Table of the shoebox datasets in docs/datasets.yaml, with the metadata each dataset's own files record.

Per registry entry it reads `dataset.yaml` (reflections, box, mode, cell,
space group, beam centre, raw count mean and variance, physics.source) and
the header of `counts.npy` (dtype, size on disk), checks whether the stored
counts are whole numbers on --sample random rows (int dtypes are by
construction), and counts the tracked configs under configs/ whose
`data_dir` is that path. Writes a Markdown table and a CSV with the same
columns. Run where the data are (the cluster checkout):

    python scripts/dataset_table.py --out-md docs/datasets.md --out-csv docs/datasets.csv
"""

from __future__ import annotations

import argparse
import csv
import subprocess
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]


def config_uses(path: str) -> int:
    out = subprocess.run(["git", "-C", str(ROOT), "grep", "-l", "-F", path, "--", "configs"],
                         capture_output=True, text=True).stdout
    return len([ln for ln in out.splitlines() if ln.strip()])


def row(entry: dict, sample: int, rng) -> dict:
    p = Path(entry["path"])
    r = dict(name=entry["name"], kind=entry["kind"], images=entry.get("images", ""),
             reflections_from=entry.get("reflections_from", ""), path=str(p))
    spec_path = p / "dataset.yaml"
    if not spec_path.exists():
        r["status"] = "missing dataset.yaml"
        return r
    spec = yaml.safe_load(spec_path.read_text())
    g = spec.get("geometry", {})
    cr = spec.get("crystal", {}) or {}
    st = (spec.get("stats", {}) or {}).get("raw", [None, None])
    counts = p / (spec.get("files", {}) or {}).get("counts", "counts.npy")
    c = np.load(counts, mmap_mode="r")
    if np.issubdtype(c.dtype, np.integer):
        integer = "yes (int dtype)"
    else:
        idx = np.sort(rng.choice(c.shape[0], size=min(sample, c.shape[0]), replace=False))
        v = np.asarray(c[idx], dtype=np.float64)
        v = v[np.isfinite(v)]
        frac = float(np.mean(v % 1 != 0))
        integer = "yes (float, all whole)" if frac == 0 else f"no ({frac:.1%} non-integer)"
    cell = cr.get("cell")
    bc = cr.get("beam_center_px")
    r.update(
        status="ok",
        mode="poly" if spec.get("polychromatic") else "mono",
        n_reflections=spec.get("n_reflections"),
        box=f"{g.get('h')}x{g.get('w')}" + (f"x{g['d']}" if g.get("d", 1) != 1 else ""),
        counts_dtype=str(c.dtype),
        integer=integer,
        counts_gb=round(counts.stat().st_size / 1e9, 2),
        raw_mean=None if st[0] is None else round(float(st[0]), 2),
        raw_var=None if st[1] is None else round(float(st[1]), 1),
        space_group=cr.get("space_group", ""),
        cell=" ".join(f"{x:.2f}" for x in cell[:3]) if cell else "",
        beam_center_px=" ".join(f"{x:.1f}" for x in bc) if bc else "",
        source=((spec.get("physics", {}) or {}).get("source", "")),
        configs=config_uses(str(p)),
    )
    return r


COLS = ["name", "kind", "mode", "n_reflections", "box", "counts_dtype", "integer", "counts_gb", "raw_mean",
        "raw_var", "space_group", "cell", "beam_center_px", "configs", "images", "reflections_from", "source",
        "path", "status"]
MD_COLS = ["name", "kind", "mode", "n_reflections", "box", "counts_dtype", "integer", "counts_gb", "raw_mean",
           "raw_var", "space_group", "cell", "configs", "images", "reflections_from"]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--registry", default=str(ROOT / "docs" / "datasets.yaml"))
    ap.add_argument("--out-md", required=True)
    ap.add_argument("--out-csv", required=True)
    ap.add_argument("--sample", type=int, default=2000)
    a = ap.parse_args()
    rng = np.random.default_rng(0)
    rows = [row(e, a.sample, rng) for e in yaml.safe_load(Path(a.registry).read_text())["datasets"]]
    with open(a.out_csv, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLS, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    fmt = lambda v: "" if v is None else (f"{v:,}" if isinstance(v, int) and not isinstance(v, bool) else str(v))
    lines = ["# Shoebox datasets", "",
             "Generated by `scripts/dataset_table.py` from `docs/datasets.yaml` and each dataset's own `dataset.yaml` "
             "and `counts.npy`; do not edit by hand.",
             "`raw_mean` and `raw_var` are the stored counts' mean and variance over valid pixels, in the dataset's "
             "units; `configs` is the number of tracked configs whose `data_dir` is the path.",
             "Paths and the remaining columns are in `docs/datasets.csv`.", "",
             "| " + " | ".join(MD_COLS) + " |", "|" + "---|" * len(MD_COLS)]
    lines += ["| " + " | ".join(fmt(r.get(k)) for k in MD_COLS) + " |" for r in rows]
    Path(a.out_md).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
